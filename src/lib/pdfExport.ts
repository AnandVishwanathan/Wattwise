import { jsPDF } from 'jspdf';
import autoTable from 'jspdf-autotable';
import type { ReportData } from '../types';

export const generateMonthlyReport = (data: ReportData) => {
  const doc = new jsPDF();
  const pageWidth = doc.internal.pageSize.getWidth();

  // Header
  doc.setFillColor(7, 9, 15); // --bg
  doc.rect(0, 0, pageWidth, 40, 'F');
  
  doc.setTextColor(0, 214, 143); // --accent
  doc.setFontSize(24);
  doc.setFont('helvetica', 'bold');
  doc.text('WattWise Energy Report', 14, 25);
  
  doc.setTextColor(238, 242, 255); // --text-1
  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.text(`${data.month} 2024`, pageWidth - 40, 25);

  // User Info & Summary
  doc.setTextColor(15, 23, 42); // dark for body
  doc.setFontSize(14);
  doc.setFont('helvetica', 'bold');
  doc.text(`Summary for ${data.userName}`, 14, 55);

  const summaryData = [
    ['Total Consumption', `${data.totalKwh.toFixed(1)} kWh`],
    ['Estimated Bill', `₹${data.totalCost.toFixed(0)}`],
    ['Carbon Footprint', `${data.co2Kg.toFixed(1)} kg CO2`],
    ['Habit Score', `${data.habitScore}/100`],
    ['Current Streak', `${data.streakDays} days`],
    ['Green Credits', `${data.greenCredits}`]
  ];

  autoTable(doc, {
    startY: 60,
    head: [['Metric', 'Value']],
    body: summaryData,
    theme: 'striped',
    headStyles: { fillColor: [0, 214, 143] }
  });

  // Top Appliances Table
  const finalY = (doc as any).lastAutoTable.finalY + 15;
  doc.setFontSize(14);
  doc.setFont('helvetica', 'bold');
  doc.text('Top Appliances', 14, finalY);

  const appliancesBody = data.topAppliances.map(app => [
    app.name,
    `${app.kWh.toFixed(1)} kWh`,
    `₹${app.cost.toFixed(0)}`,
    `${((app.kWh / data.totalKwh) * 100).toFixed(0)}%`
  ]);

  autoTable(doc, {
    startY: finalY + 5,
    head: [['Appliance', 'Usage', 'Cost', '% of Total']],
    body: appliancesBody,
    theme: 'grid',
    headStyles: { fillColor: [12, 16, 24] }
  });

  // AI Savings Tips
  const tipsY = (doc as any).lastAutoTable.finalY + 15;
  doc.setFontSize(14);
  doc.setFont('helvetica', 'bold');
  doc.text('Personalized Savings Tips', 14, tipsY);

  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  data.tips.slice(0, 4).forEach((tip, index) => {
    const text = `${index + 1}. ${tip.appliance}: ${tip.action} (Save ₹${tip.savingRupees}/mo)`;
    doc.text(text, 14, tipsY + 10 + (index * 7));
  });

  // Footer
  const pageHeight = doc.internal.pageSize.getHeight();
  doc.setFontSize(8);
  doc.setTextColor(100, 116, 139);
  doc.text('Generated by WattWise AI - Your Sustainable Energy Partner', pageWidth / 2, pageHeight - 10, { align: 'center' });

  // Save the PDF
  doc.save(`WattWise_Report_${data.month}_${data.userName.replace(/\s+/g, '_')}.pdf`);
};
